export type OutfitPart = { file: string; folder: string; node: string };

/** The mesh parts an appearance is made of (base regions + items), independent of LOD. */
export function outfitParts(a: AvatarAppearance): OutfitPart[] {
    const items = [a.topId, a.bottomId, a.shoesId, a.hairId, a.headwearId, a.backId, a.weaponSkinId].map((id) => WARDROBE_CATALOG[id]);
    const hidden = new Set<BaseRegion>(items.flatMap((i) => i?.hides ?? []));
    const capped = a.headwearId !== 'none';
    const parts: OutfitPart[] = [
        { file: 'courier_base', folder: 'characters', node: 'base_head' },
        { file: 'courier_base', folder: 'characters', node: 'base_hands' }
    ];
    for (const r of BASE_REGIONS) if (!hidden.has(r)) parts.push({ file: 'courier_base', folder: 'characters', node: `base_${r}` });
    for (const item of items) {
        if (!item?.file) continue;
        const node = item.slot === 'hair' && capped ? 'hair_capped' : item.node;
        parts.push({ file: item.file, folder: item.folder, node });
    }
    return parts;
}

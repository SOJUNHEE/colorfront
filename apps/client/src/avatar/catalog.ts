export type OutfitPart = { file: string; folder: string; node: string };

/** The mesh parts an appearance (+ the carried weapon) is made of, independent of LOD. */
export function outfitParts(a: AvatarAppearance, weapon: WeaponId = 'paint-rifle'): OutfitPart[] {
    const ids = [a.topId, a.bottomId, a.shoesId, a.hairId, a.headwearId, a.faceId, a.neckId, a.backId];
    const items = ids.map((id) => WARDROBE_CATALOG[id]).filter((x): x is WardrobeItemDef => !!x);
    const hidden = new Set<BaseRegion>(items.flatMap((i) => i.hides));
    const capped = a.headwearId !== 'none';
    const parts: OutfitPart[] = [
        { file: 'courier_base', folder: 'characters', node: 'base_head' },
        { file: 'courier_base', folder: 'characters', node: 'base_hands' }
    ];
    for (const r of BASE_REGIONS) if (!hidden.has(r)) parts.push({ file: 'courier_base', folder: 'characters', node: `base_${r}` });
    for (const it of items) {
        if (!it.file) continue;
        const node = it.slot === 'hair' && capped ? 'hair_capped' : it.node;
        parts.push({ file: it.file, folder: it.folder, node });
    }
    parts.push({ file: WEAPON_MODELS[weapon].file, folder: 'weapons', node: 'weapon' });
    return parts;
}

import type { AvatarAppearance, WardrobeSlot } from '@colorfront/shared';

/**
 * Client-side wardrobe catalog: which GLB holds an item, which mesh nodes it contributes and which
 * base-body regions it hides. IDs come from the shared allowlist (WARDROBE_ITEMS); assets are
 * built by assets-src/blender/scripts/build_courier.py as `<file>_lod<0..2>.glb`.
 */

/** Base body regions an item can hide (head and hands are always drawn). */
export type BaseRegion = 'torso' | 'upperarms' | 'forearms' | 'hips' | 'thighs' | 'knees' | 'shins' | 'feet';
export const BASE_REGIONS: readonly BaseRegion[] = ['torso', 'upperarms', 'forearms', 'hips', 'thighs', 'knees', 'shins', 'feet'];

export type WardrobeItemDef = {
    slot: WardrobeSlot;
    label: string;
    /** GLB name under /assets/<folder>/ without the `_lod<n>.glb` suffix (null = nothing drawn). */
    file: string | null;
    folder: 'clothes' | 'weapons';
    /** Mesh node(s) taken from the file. Hair: `hair`, or `hair_capped` under headwear. */
    node: string;
    hides: readonly BaseRegion[];
    license: string;
};


# ── procedural 2D drawing (numpy, supersampled) ──────────────────────────────────────────────────
def smooth_mask(sdf, aa):
    return np.clip(0.5 - sdf / aa, 0.0, 1.0)


def sd_ellipse(px, py, cx, cy, a, b):
    k = np.sqrt(((px - cx) / a) ** 2 + ((py - cy) / b) ** 2)
    return (k - 1.0) * min(a, b)


def sd_capsule(px, py, ax, ay, bx, by, r):
    pax, pay = px - ax, py - ay
    bax, bay = bx - ax, by - ay
    h = np.clip((pax * bax + pay * bay) / (bax * bax + bay * bay), 0.0, 1.0)
    return np.sqrt((pax - bax * h) ** 2 + (pay - bay * h) ** 2) - r


def sd_polyline(px, py, pts, r):
    d = None
    for (ax, ay), (bx, by) in zip(pts[:-1], pts[1:]):
        s = sd_capsule(px, py, ax, ay, bx, by, r)
        d = s if d is None else np.minimum(d, s)
    return d


def blend(img, mask, rgb, alpha=1.0):
    m = (mask * alpha)[..., None]
    img[..., :3] = img[..., :3] * (1 - m) + np.array(rgb)[None, None, :] * m


def arc_pts(cx, cy, rx, ry, a0, a1, n=24):
    return [(cx + rx * math.cos(a0 + (a1 - a0) * i / n), cy + ry * math.sin(a0 + (a1 - a0) * i / n)) for i in range(n + 1)]


SKIN = hex_rgb('#F2C4A2')
INK = hex_rgb('#1F1A24')
BROW = hex_rgb('#2B2E44')


def draw_face(expr, skin=None, size=256, ss=4):
    """One face tile. Tile coords: u = (x + 0.18) / 0.36, v = (y - 1.22) / 0.36 (runtime metres)."""
    n = size * ss
    ys, xs = np.mgrid[0:n, 0:n]
    u = (xs + 0.5) / n
    v = (ys + 0.5) / n  # row 0 = bottom (Blender pixel order)
    img = np.zeros((n, n, 4), dtype=np.float32)
    img[..., :3] = SKIN if skin is None else skin
    img[..., 3] = 1
    aa = 1.5 / n
    # Cheeks.
    for sx in (-1, 1):
        blend(img, smooth_mask(sd_ellipse(u, v, 0.5 + sx * 0.255, 0.31, 0.065, 0.032), 0.03), hex_rgb('#F59A8C'), 0.45)
    eye_v = 0.455
    for sx in (-1, 1):
        cx = 0.5 + sx * 0.2
        if expr in ('neutral', 'surprised'):
            big = expr == 'surprised'
            a, b = (0.085, 0.112) if big else (0.08, 0.105)
            sclera = sd_ellipse(u, v, cx, eye_v, a, b)
            blend(img, smooth_mask(sclera, aa), hex_rgb('#FDFBF7'))
            # Iris (looks slightly inward), with a darker top.
            icx, icy = cx - sx * 0.012, eye_v - 0.008
            ia, ib = (0.045, 0.058) if big else (0.061, 0.08)
            iris = sd_ellipse(u, v, icx, icy, ia, ib)
            inside = smooth_mask(np.maximum(iris, sclera), aa)
            t = np.clip((v - (icy - ib)) / (2 * ib), 0, 1)[..., None]
            top, bot = np.array(hex_rgb('#3A2516')), np.array(hex_rgb('#B87A3D'))
            col = bot * (1 - t) + top * t
            m = inside[..., None]
            img[..., :3] = img[..., :3] * (1 - m) + col * m
            blend(img, smooth_mask(np.maximum(sd_ellipse(u, v, icx, icy, ia * 0.48, ib * 0.5), sclera), aa), INK)
            blend(img, smooth_mask(sd_ellipse(u, v, icx + 0.02, icy + 0.03, 0.019, 0.022), aa), [1, 1, 1])
            blend(img, smooth_mask(sd_ellipse(u, v, icx - 0.018, icy - 0.03, 0.009, 0.009), aa), [1, 1, 1], 0.9)
            # Upper lid: thick ink line over the top of the eye, with an outer flick.
            lid = arc_pts(cx, eye_v, a + 0.004, b + 0.004, math.radians(15), math.radians(165))
            lid.append((cx + sx * (a + 0.03), eye_v + b * 0.45))
            lid = sorted(lid, key=lambda p: p[0])
            blend(img, smooth_mask(sd_polyline(u, v, lid, 0.011), aa), INK)
        elif expr == 'blink':
            pts = arc_pts(cx, eye_v + 0.03, 0.085, 0.05, math.radians(200), math.radians(340))
            blend(img, smooth_mask(sd_polyline(u, v, pts, 0.012), aa), INK)
        elif expr == 'happy':
            pts = arc_pts(cx, eye_v - 0.03, 0.075, 0.075, math.radians(20), math.radians(160))
            blend(img, smooth_mask(sd_polyline(u, v, pts, 0.014), aa), INK)
        # Brows: thick, angled (confident), raised when surprised.
        lift = 0.05 if expr == 'surprised' else 0.0
        inner = (0.5 + sx * 0.11, 0.635 + lift)
        outer = (0.5 + sx * 0.29, 0.672 + lift + (0.01 if expr == 'happy' else 0))
        blend(img, smooth_mask(sd_capsule(u, v, inner[0], inner[1], outer[0], outer[1], 0.019), aa), BROW)
    # Mouth.
    if expr == 'happy':
        mouth = sd_ellipse(u, v, 0.5, 0.215, 0.075, 0.06)
        mouth = np.maximum(mouth, v - 0.215)
        blend(img, smooth_mask(mouth, aa), hex_rgb('#6E2B32'))
        blend(img, smooth_mask(np.maximum(sd_ellipse(u, v, 0.5, 0.16, 0.04, 0.025), mouth), aa), hex_rgb('#E0727A'))
    elif expr == 'surprised':
        blend(img, smooth_mask(sd_ellipse(u, v, 0.5, 0.2, 0.032, 0.042), aa), hex_rgb('#6E2B32'))
    else:
        pts = [(0.5 + t * 0.065, 0.215 + 0.6 * (t * 0.065) ** 2 * 10) for t in np.linspace(-1, 1, 15)]
        blend(img, smooth_mask(sd_polyline(u, v, pts, 0.009), aa), hex_rgb('#7A3638'))
    return img.reshape(size, ss, size, ss, 4).mean(axis=(1, 3))


def draw_emblem(team, size=128, ss=4):
    n = size * ss
    ys, xs = np.mgrid[0:n, 0:n]
    u = (xs + 0.5) / n
    v = (ys + 0.5) / n
    img = np.zeros((n, n, 4), dtype=np.float32)
    img[..., 3] = 1
    img[..., :3] = hex_rgb(TEAMS[team]['team'])
    aa = 1.5 / n
    ivory = hex_rgb('#EEE8DB')
    if team == 'blue':
        # Two diagonal stripes.
        for off in (-0.16, 0.16):
            d = np.abs((u - 0.5) - (v - 0.5) + off) / math.sqrt(2) - 0.07
            blend(img, smooth_mask(d, aa), ivory)
    else:
        # Shield outline with a centre dot.
        shield = np.maximum(sd_ellipse(u, v, 0.5, 0.56, 0.3, 0.34), v - 0.8)
        ring = np.abs(shield) - 0.045
        blend(img, smooth_mask(ring, aa), ivory)
        blend(img, smooth_mask(sd_ellipse(u, v, 0.5, 0.52, 0.1, 0.1), aa), ivory)
    return img.reshape(size, ss, size, ss, 4).mean(axis=(1, 3))


def build_textures():
    """Write the shared atlas (full res), ORM (R=AO, G=roughness, B=metal) and emissive (half res)."""
    base = np.zeros((ATLAS_H, ATLAS_W, 4), dtype=np.float32)
    base[..., :3] = hex_rgb('#808080')
    base[..., 3] = 1
    orm = np.zeros_like(base)
    orm[..., 0] = 1
    orm[..., 1] = 0.6
    orm[..., 3] = 1
    emi = np.zeros_like(base)
    emi[..., 3] = 1
    for i, cell in enumerate(CELLS):
        if not cell:
            continue
        name, col, rough, metal, glow = cell
        rgb = hex_rgb(col)
        c, r = i % 8, i // 8
        rs, cs = slice(r * CELL, (r + 1) * CELL), slice(c * CELL, (c + 1) * CELL)
        base[rs, cs, :3] = rgb
        orm[rs, cs, 1] = rough
        orm[rs, cs, 2] = metal
        if glow:
            emi[rs, cs, :3] = np.array(rgb) * glow
    for team, (c, r) in EMBLEMS.items():
        base[r * CELL:(r + 2) * CELL, c * CELL:(c + 2) * CELL] = draw_emblem(team)
        orm[r * CELL:(r + 2) * CELL, c * CELL:(c + 2) * CELL, 1] = 0.5
    for t, (_, skin, _) in enumerate(SKIN_TONES):
        for e, expr in enumerate(EXPRESSIONS):
            ys, xs = slice(t * FACE_TILE, (t + 1) * FACE_TILE), slice(512 + e * FACE_TILE, 512 + (e + 1) * FACE_TILE)
            base[ys, xs] = draw_face(expr, hex_rgb(skin), size=FACE_TILE, ss=3)
            orm[ys, xs, 1] = 0.5

    def half(a):
        return a.reshape(ATLAS_H // 2, 2, ATLAS_W // 2, 2, 4).mean(axis=(1, 3))
    paths = {}
    for kind, arr in (('atlas', base), ('orm', half(orm)), ('emissive', half(emi))):
        p = os.path.join(TEX, f'courier_{kind}.png')
        save_png(p, arr, f'courier_{kind}')
        paths[kind] = p
    write_layout()
    return {('atlas', 'blue'): paths['atlas'], ('atlas', 'orange'): paths['atlas'], ('emissive', 'blue'): paths['emissive'],
            ('emissive', 'orange'): paths['emissive'], ('orm', None): paths['orm']}


def save_png(path, arr, name):
    h, w = arr.shape[:2]
    img = bpy.data.images.new(name + '_tmp', w, h, alpha=True)
    img.pixels.foreach_set(np.clip(arr, 0, 1).astype(np.float32).ravel())
    img.filepath_raw = path
    img.file_format = 'PNG'
    img.save()
    bpy.data.images.remove(img)



def build_gun(d):
    ox, oy, oz = GUN_ORIGIN
    parts = []

    def G(x, y, z):
        return (ox + x, oy + y, oz + z)
    body = rbox('gbody', G(0, 0.0, -0.22), (0.072, 0.09, 0.36), bevel=L(d, 0.6, 0.6, 0), segs=1)

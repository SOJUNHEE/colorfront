def tri_count(obj):
    return tris(obj)


def build_lod(d, arm, S, body_mat, glass_mat, items=None):
    global COLL, ARM_REF, SKEL
    ARM_REF, SKEL = arm, S
    COLL = bpy.data.collections.new(f'LOD{d}')
    bpy.context.scene.collection.children.link(COLL)
    head = build_head(d)
    hair = build_hair(d)
    top = build_jacket(d)
    bottom = build_pants(d)
    shoes = build_shoes(d)
    gloves = build_gloves(d)
    back = build_tank(d)
    gun = build_gun(d)
    base = build_base_body(d) if items is not None else None
    for o in (head, hair, top, bottom, shoes, gloves, back, gun) + ((base,) if base else ()):
        limit_normalize(o)
    stats = {'parts': {n: tris(o) for n, o in (('head', head), ('hair', hair), ('top', top), ('bottom', bottom),
                                                ('shoes', shoes), ('gloves', gloves), ('back', back), ('gun', gun))}}
    if items is not None:
        # Wardrobe item GLBs (LOD0 only). Base = body + head + gloves.
        groups = {
            'courier_base_lod0': (OUT_CHAR, [base, head, gloves]),
            'top_bomber': (OUT_CLOTH, [top]),
            'bottom_cargo': (OUT_CLOTH, [bottom]),
            'shoes_runner': (OUT_CLOTH, [shoes]),
            'hair_sidepart': (OUT_CLOTH, [hair]),
            'back_tank_standard': (OUT_CLOTH, [back]),
            'paint_rifle': (OUT_WEAP, [gun]),
        }
        for name, (folder, objs) in groups.items():
            copies = []
            for o in objs:
                c = o.copy()
                c.data = o.data.copy()
                COLL.objects.link(c)
                copies.append(c)
            m = join(copies, name) if len(copies) > 1 else copies[0]
            m.name = name
            attach(m, arm)
            items[name] = (folder, m)
            stats[name] = tri_count(m)
    full = join([head, hair, top, bottom, shoes, gloves, back, gun], f'courier_default_lod{d}')
    attach(full, arm)
    stats['default'] = tri_count(full)
    if base is not None:
        bpy.data.objects.remove(base)
    return full, stats, {}



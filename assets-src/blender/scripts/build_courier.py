    if d == 2:
        g = join(parts, 'gun_part')
        rigid_weights(g, 'gun')
        return g
    parts.append(finish(rbox('grip', G(0, -0.075, 0.0), (0.04, 0.1, 0.045), bevel=0.6, segs=1,
                             taper=lambda x, y, z: (x, y, z + y * 0.35)), 'rubber', sharp=50))

    parts.append(finish(body, rule=lambda p, n, poly: 'ivory' if p[1] > oy + 0.02 else 'graphite', sharp=40))
    can = cylinder('canister', G(0, 0.068, -0.1), G(0, 0.068, -0.31), 0.036, segs=L(d, 14, 8, 6))
    parts.append(finish(can, 'team', sharp=50))
    if d < 2:
        parts.append(finish(rbox('canwin', G(0.035, 0.068, -0.205), (0.006, 0.026, 0.13), bevel=0.4, segs=1), 'led'))
    parts.append(finish(cylinder('barrel', G(0, 0.03, -0.39), G(0, 0.03, -0.6), 0.02, segs=[12, 8, 6][d]), 'metal', sharp=50))

def select_only(objs, active):
    bpy.ops.object.select_all(action='DESELECT')
    for o in objs:
        o.select_set(True)
    bpy.context.view_layer.objects.active = active


def heat_weights(obj, arm_obj, S):
    """Blender bone-heat weights (deforming body/clothes), unweighted vertices -> nearest bone."""
    for b in arm_obj.data.bones:
        b.use_deform = b.name not in NON_DEFORM_FOR_HEAT
    select_only([obj, arm_obj], arm_obj)
    bpy.ops.object.parent_set(type='ARMATURE_AUTO')
    for b in arm_obj.data.bones:
        b.use_deform = True
    fixed = nearest_bone_fill(obj, S)
    HEAT_FALLBACK.append((obj.name, fixed, len(obj.data.vertices)))
    limit_normalize(obj)
    # Detach (keep groups); the final joined mesh gets one armature modifier.
    for m in list(obj.modifiers):
        obj.modifiers.remove(m)
    obj.parent = None
    return fixed


def seg_dist(p, a, b):
    ab = b - a
    t = max(0.0, min(1.0, (p - a).dot(ab) / max(1e-9, ab.dot(ab))))
    return (a + ab * t - p).length


def nearest_bone_fill(obj, S):
    deform = [n for n in S if n not in NON_DEFORM_FOR_HEAT]
    segs = {n: (R(*S[n][1]), R(*S[n][2])) for n in deform}
    groups = {g.index: g.name for g in obj.vertex_groups}
    fixed = 0
    for v in obj.data.vertices:
        if any(g.weight > 1e-4 and groups.get(g.group) in segs for g in v.groups):
            continue
        best = min(deform, key=lambda n: seg_dist(v.co, *segs[n]))
        vg = obj.vertex_groups.get(best) or obj.vertex_groups.new(name=best)
        vg.add([v.index], 1.0, 'REPLACE')
        fixed += 1
    return fixed


def limit_normalize(obj):
    select_only([obj], obj)
    bpy.ops.object.vertex_group_limit_total(group_select_mode='ALL', limit=4)
    bpy.ops.object.vertex_group_normalize_all(group_select_mode='ALL', lock_active=False)


def rigid_weights(obj, bone):
    vg = obj.vertex_groups.new(name=bone)
    vg.add([v.index for v in obj.data.vertices], 1.0, 'REPLACE')


def rule_weights(obj, fn):
    """fn(runtime xyz) -> {bone: weight}."""
    for v in obj.data.vertices:
        for bone, w in fn(to_runtime(v.co)).items():
            if w <= 0:
                continue
            vg = obj.vertex_groups.get(bone) or obj.vertex_groups.new(name=bone)
            vg.add([v.index], w, 'REPLACE')


def head_neck_weights(p):
    y = p[1]
    if y >= 1.25:
        return {'head': 1.0}
    if y <= 1.12:
        return {'chest': 1.0}
    if y <= 1.18:
        t = (y - 1.12) / 0.06
        return {'chest': 1 - t, 'neck': t}
    t = (y - 1.18) / 0.07
    return {'neck': 1 - t, 'head': t}


def join(objs, name):
    objs = [o for o in objs if o]
    select_only(objs, objs[0])
    bpy.ops.object.join()
    o = bpy.context.view_layer.objects.active
    o.name = name
    o.data.name = name
    return o



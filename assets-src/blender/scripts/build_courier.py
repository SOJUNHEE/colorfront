def straighten_bones(arm_obj):
    """Point every bone along +Z (Blender) with zero roll. Bone axes then equal world axes, so the
    exported glTF joints have IDENTITY rest rotations (same convention as CharacterRig), and the
    joint translations equal the head offsets. Skin weights are unaffected (rest = identity)."""
    bpy.context.view_layer.objects.active = arm_obj
    bpy.ops.object.mode_set(mode='EDIT')
    for eb in arm_obj.data.edit_bones:
        eb.use_connect = False
    for eb in arm_obj.data.edit_bones:
        eb.tail = eb.head + Vector((0, 0, 0.08))
        eb.roll = 0
    bpy.ops.object.mode_set(mode='OBJECT')



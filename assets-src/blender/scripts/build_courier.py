def make_materials(paths, team='blue'):
    body = bpy.data.materials.new('cf_body')
    body.use_nodes = True
    nt = body.node_tree
    bsdf = nt.nodes.get('Principled BSDF')
    base = nt.nodes.new('ShaderNodeTexImage')
    base.image = bpy.data.images.load(paths[('atlas', team)])
    base.image.name = 'courier_atlas'
    base.interpolation = 'Linear'
    orm = nt.nodes.new('ShaderNodeTexImage')
    orm.image = bpy.data.images.load(paths[('orm', None)])
    orm.image.colorspace_settings.name = 'Non-Color'
    orm.image.name = 'courier_orm'
    sep = nt.nodes.new('ShaderNodeSeparateColor')
    emi = nt.nodes.new('ShaderNodeTexImage')
    emi.image = bpy.data.images.load(paths[('emissive', team)])
    emi.image.name = 'courier_emissive'
    nt.links.new(base.outputs['Color'], bsdf.inputs['Base Color'])
    nt.links.new(orm.outputs['Color'], sep.inputs['Color'])
    nt.links.new(sep.outputs['Green'], bsdf.inputs['Roughness'])
    nt.links.new(sep.outputs['Blue'], bsdf.inputs['Metallic'])
    nt.links.new(emi.outputs['Color'], bsdf.inputs['Emission Color'])
    bsdf.inputs['Emission Strength'].default_value = 1.0

    glass = bpy.data.materials.new('cf_glass')
    glass.use_nodes = True
    g = glass.node_tree.nodes.get('Principled BSDF')
    g.inputs['Base Color'].default_value = (*[c ** 2.2 for c in hex_rgb('#DCE8F2')], 1)
    g.inputs['Roughness'].default_value = 0.04
    g.inputs['Alpha'].default_value = 0.28
    try:
        glass.surface_render_method = 'BLENDED'
    except AttributeError:
        glass.blend_method = 'BLEND'
    return body, glass


# ── mesh helpers ─────────────────────────────────────────────────────────────────────────────────
COLL = None
MATS = []


def link(obj):
    COLL.objects.link(obj)
    return obj


def obj_from_bm(name, bm):
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    return link(bpy.data.objects.new(name, me))


def bake(obj):
    """Apply all modifiers / convert curves to a plain mesh object (no bpy.ops needed)."""
    dg = bpy.context.evaluated_depsgraph_get()
    me = bpy.data.meshes.new_from_object(obj.evaluated_get(dg), preserve_all_data_layers=True, depsgraph=dg)
    new = link(bpy.data.objects.new(obj.name, me))
    new.matrix_world = obj.matrix_world
    old = obj.name
    bpy.data.objects.remove(obj)
    new.name = old
    me.transform(new.matrix_world)
    new.matrix_world = Matrix.Identity(4)
    return new


def ellipsoid(name, center, radii, segs=(24, 12), shape=None):
    """UV sphere deformed in runtime space. `shape(x,y,z)` (unit sphere coords) -> (x,y,z)."""
    bm = bmesh.new()
    bmesh.ops.create_uvsphere(bm, u_segments=segs[0], v_segments=segs[1], radius=1.0)
    for v in bm.verts:
        x, y, z = v.co.x, v.co.z, -v.co.y  # Blender sphere -> runtime unit coords
        if shape:
            x, y, z = shape(x, y, z)
        v.co = R(center[0] + x * radii[0], center[1] + y * radii[1], center[2] + z * radii[2])
    return obj_from_bm(name, bm)


def rbox(name, center, size, bevel=0.3, segs=2, taper=None, subdiv=0):
    """Rounded box in runtime space. bevel = fraction of the smallest half-size."""
    bm = bmesh.new()
    bmesh.ops.create_cube(bm, size=1.0)
    for v in bm.verts:
        x, y, z = v.co.x * size[0], v.co.z * size[1], -v.co.y * size[2]
        if taper:
            x, y, z = taper(x, y, z)
        v.co = R(center[0] + x, center[1] + y, center[2] + z)
    if bevel > 0:
        w = min(size) * 0.5 * bevel
        bmesh.ops.bevel(bm, geom=list(bm.edges) + list(bm.verts), offset=w, segments=segs, affect='EDGES', profile=0.5)
    o = obj_from_bm(name, bm)
    if subdiv:
        m = o.modifiers.new('sub', 'SUBSURF')
        m.levels = subdiv
        o = bake(o)
    return o


def cylinder(name, a, b, r1, r2=None, segs=16, caps=True):
    """Cylinder/cone between runtime points a and b."""
    r2 = r1 if r2 is None else r2
    bm = bmesh.new()
    bmesh.ops.create_cone(bm, cap_ends=caps, cap_tris=False, segments=segs, radius1=r1, radius2=r2, depth=1.0)
    A, B = R(*a), R(*b)
    d = B - A
    rot = Vector((0, 0, 1)).rotation_difference(d.normalized()).to_matrix().to_4x4()
    mat = Matrix.Translation((A + B) / 2) @ rot @ Matrix.Diagonal((1, 1, d.length, 1))
    bmesh.ops.transform(bm, matrix=mat, verts=bm.verts)
    return obj_from_bm(name, bm)


def torus(name, center, rx, rz, r_minor, axis=(0, 1, 0), segs=(24, 8)):
    """Elliptic ring (radii rx, rz around runtime `axis`) with a round tube of radius `r_minor`.
    The tube thickness is independent of the ring size."""
    bm = bmesh.new()
    rings = []
    for i in range(segs[0]):
        a = 2 * math.pi * i / segs[0]
        # Ring point and outward normal of the ellipse in the local XZ plane (local axis = +Y).
        px, pz = rx * math.cos(a), rz * math.sin(a)
        nx, nz = math.cos(a) / rx, math.sin(a) / rz
        nl = math.hypot(nx, nz)
        nx, nz = nx / nl, nz / nl
        ring = []
        for j in range(segs[1]):
            b = 2 * math.pi * j / segs[1]
            off_r, off_y = r_minor * math.cos(b), r_minor * math.sin(b)
            ring.append(bm.verts.new(R(px + nx * off_r, off_y, pz + nz * off_r)))
        rings.append(ring)
    for i in range(segs[0]):
        for j in range(segs[1]):
            a, b = rings[i][j], rings[i][(j + 1) % segs[1]]
            c, d = rings[(i + 1) % segs[0]][(j + 1) % segs[1]], rings[(i + 1) % segs[0]][j]
            bm.faces.new((a, b, c, d))
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    # Local axis = runtime +Y = Blender +Z; rotate onto `axis`, then move to `center`.
    rot = Vector((0, 0, 1)).rotation_difference(R(*axis).normalized()).to_matrix().to_4x4()
    bmesh.ops.transform(bm, matrix=Matrix.Translation(R(*center)) @ rot, verts=bm.verts)
    return obj_from_bm(name, bm)


def skin_body(name, nodes, edges, root=0, subdiv=2):
    """Connected organic hull from a node graph (runtime positions + (rx, ry) radii)."""
    me = bpy.data.meshes.new(name)
    me.from_pydata([R(*p) for p, _ in nodes], edges, [])
    o = link(bpy.data.objects.new(name, me))
    sk = o.modifiers.new('skin', 'SKIN')
    if not me.skin_vertices:
        me.skin_vertices.new()
    sk.branch_smoothing = 0.6
    sk.use_smooth_shade = True
    for i, (_, rad) in enumerate(nodes):
        sv = me.skin_vertices[0].data[i]
        sv.radius = rad
        sv.use_root = i == root
    if subdiv:
        s = o.modifiers.new('sub', 'SUBSURF')
        s.levels = subdiv
        s.render_levels = subdiv
    return bake(o)


_PROFILES = {}


def _profile_obj(sides, flat):
    """Elliptic bevel profile (unit width, `flat` height) for flattened tubes (straps, bands)."""
    key = (sides, flat)
    if key not in _PROFILES:
        cu = bpy.data.curves.new(f'profile_{sides}_{flat}', 'CURVE')
        sp = cu.splines.new('POLY')
        n = sides
        sp.points.add(n - 1)
        for i, pt in enumerate(sp.points):
            a = 2 * math.pi * i / n
            pt.co = (math.cos(a), math.sin(a) * flat, 0, 1)
        sp.use_cyclic_u = True
        o = bpy.data.objects.new(cu.name, cu)
        bpy.context.scene.collection.objects.link(o)
        o.hide_render = True
        o.hide_set(True)
        _PROFILES[key] = o
    return _PROFILES[key]


def tube(name, pts, radii, res=6, sides=2, flat=None, caps=True, tilt=0.0):
    """Tapered curve tube through runtime points (hair locks, frame arches, straps).
    `flat` (0..1) flattens the cross-section into a ribbon (sides = ring vertex count then)."""
    cu = bpy.data.curves.new(name, 'CURVE')
    cu.dimensions = '3D'
    cu.resolution_u = res
    if flat:
        cu.bevel_mode = 'OBJECT'
        cu.bevel_object = _profile_obj(max(6, sides), flat)
    else:
        cu.bevel_mode = 'ROUND'
        cu.bevel_depth = 1.0
        cu.bevel_resolution = sides
    cu.use_fill_caps = caps
    sp = cu.splines.new('BEZIER')
    sp.bezier_points.add(len(pts) - 1)
    for bp, p, r in zip(sp.bezier_points, pts, radii):
        bp.co = R(*p)
        bp.handle_left_type = bp.handle_right_type = 'AUTO'
        bp.radius = r
        bp.tilt = tilt
    o = link(bpy.data.objects.new(name, cu))
    return bake(o)


def tris(obj):
    return sum(len(p.vertices) - 2 for p in obj.data.polygons)


def dec_to(obj, target, symmetric=False):
    """Collapse-decimate to about `target` triangles. Called BEFORE UVs/colours are assigned, so
    palette cells can never bleed into each other."""
    n = tris(obj)
    if n <= target:
        return obj
    m = obj.modifiers.new('dec', 'DECIMATE')
    m.decimate_type = 'COLLAPSE'
    m.ratio = target / n
    m.use_collapse_triangulate = False
    if symmetric:
        m.use_symmetry = True
        m.symmetry_axis = 'X'
    return bake(obj)


def cut(obj, planes):
    """Split faces along runtime planes [(point, normal[, filter])] so colour regions get clean
    edges. `filter(face centre, runtime)` limits the cut to faces where the colour really changes."""
    bm = bmesh.new()
    bm.from_mesh(obj.data)
    for plane in planes:
        co, no = plane[0], plane[1]
        filt = plane[2] if len(plane) > 2 else None
        faces = [f for f in bm.faces if filt is None or filt(to_runtime(f.calc_center_median()))]
        edges = {e for f in faces for e in f.edges}
        verts = {v for e in edges for v in e.verts}
        geom = list(verts) + list(edges) + faces
        bmesh.ops.bisect_plane(bm, geom=geom, dist=1e-5, plane_co=R(*co), plane_no=R(*no).normalized())
    bm.to_mesh(obj.data)
    bm.free()
    return obj


def transfer_weights(src, dst, k=4):
    """Give accessory vertices the (distance-blended) weights of the nearest hull vertices, so
    pockets, pads, collars and zips follow the cloth they sit on instead of drifting."""
    from mathutils.kdtree import KDTree
    kd = KDTree(len(src.data.vertices))
    for v in src.data.vertices:
        kd.insert(v.co, v.index)
    kd.balance()
    names = {g.index: g.name for g in src.vertex_groups}
    for v in dst.data.vertices:
        acc = {}
        tot = 0.0
        for _, idx, dist in kd.find_n(v.co, k):
            w = 1.0 / max(dist, 1e-4) ** 2
            tot += w
            for g in src.data.vertices[idx].groups:
                acc[names[g.group]] = acc.get(names[g.group], 0.0) + g.weight * w
        for bone, w in acc.items():
            vg = dst.vertex_groups.get(bone) or dst.vertex_groups.new(name=bone)
            vg.add([v.index], w / tot, 'REPLACE')


def finish(obj, cell=None, rule=None, smooth=True, sharp=None, mat=0):
    """Assign UVs (palette cell / rule per face), material and shading."""
    me = obj.data
    # Both slots on every part, so joins keep material indices (slot 1 = glass).
    if len(me.materials) != len(MATS):
        me.materials.clear()
        for m in MATS:
            me.materials.append(m)
    if not me.uv_layers:
        me.uv_layers.new(name='UVMap')
    uv = me.uv_layers[0].data
    for poly in me.polygons:
        c = Vector((0, 0, 0))
        for vi in poly.vertices:
            c += me.vertices[vi].co
        c /= len(poly.vertices)
        rc = to_runtime(c)
        rn = to_runtime(poly.normal)
        res = rule(rc, rn, poly) if rule else cell
        if isinstance(res, str):
            u = cell_uv(res)
            for li in poly.loop_indices:
                uv[li].uv = u
        else:  # callable per-vertex projection
            for li, vi in zip(poly.loop_indices, poly.vertices):
                uv[li].uv = res(to_runtime(me.vertices[vi].co))
        poly.material_index = mat
    for p in me.polygons:
        p.use_smooth = smooth
    if sharp is not None:
        me.set_sharp_from_angle(angle=math.radians(sharp))
    obj['cf_mat'] = mat
    return obj



def boot_weights(side):
    def fn(p):
        y = p[1]
        if y >= 0.13:
            return {'shin' + side: 1.0}
        if y <= 0.08:
            return {'foot' + side: 1.0}
        t = (y - 0.08) / 0.05
        return {'foot' + side: 1 - t, 'shin' + side: t}
    return fn



def build_shoes(d):
    out = []
    for side in ('L', 'R'):
        sx = -1 if side == 'L' else 1
        cx = sx * 0.105
        parts = []

        def upper_taper(x, y, z):
            if z < 0:
                y = y - (-z / 0.13) * 0.032 * (y > 0)
            return x, y, z
        up = rbox('upper', (cx, 0.084, -0.04), (0.124, 0.094, 0.26), bevel=0.95, segs=L(d, 3, 2, 1), taper=upper_taper,
                  subdiv=L(d, 1, 0))
        up = dec_to(up, B('shoe_upper', d))
        sidef = lambda p, cx=cx: abs(p[0] - cx) > 0.035  # noqa: E731
        if d < 2:
            cut(up, [((0, 0.055, 0), (0, 1, 0), sidef), ((0, 0.1, 0), (0, 1, 0), sidef), ((0, 0, 0.05), (0, 0, 1), None)])

        def upper_rule(p, n, poly, cx=cx, d=d):
            x, y, z = p
            if d == 2:
                return 'team' if z > 0.05 else 'graphite_l'
            if abs(x - cx) > 0.04 and 0.055 < y < 0.1 and z < 0.05:
                return 'team'  # side band
            if z > 0.05:
                return 'team_d'  # heel counter
            return 'graphite_l'
        parts.append(finish(up, rule=upper_rule))
        sole = rbox('sole', (cx, 0.019, -0.042), (0.136, 0.038, 0.272), bevel=L(d, 0.9, 0.9, 0.5), segs=L(d, 3, 2, 1),
                    taper=lambda x, y, z: (x * (1 - 0.18 * max(0.0, -z / 0.136) ** 2), y, z))
        sole = dec_to(sole, B('sole', d))
        parts.append(finish(sole, 'sole', sharp=45))
        if d == 0:
            collar = torus('shoecollar', (cx, 0.132, 0.03), 0.06, 0.064, 0.017, segs=L(d, (12, 4), (8, 3)))
            parts.append(finish(collar, 'rubber'))
        if d == 0:
            for i in range(2):
                z = -0.03 - i * 0.034
                parts.append(finish(rbox('lace', (cx, 0.131 - i * 0.013, z), (0.066, 0.012, 0.014), bevel=0, segs=1), 'ivory'))
        s = join(parts, f'shoe{side}')
        rigid_weights(s, 'foot' + side)
        out.append(s)
    return join(out, 'shoes_part')


def build_gloves(d):
    out = []
    for side in ('L', 'R'):
        sx = -1 if side == 'L' else 1
        w = arm_point(side, 0.47)
        down = Vector((sx * math.sin(ARM_ANGLE), -math.cos(ARM_ANGLE), 0))  # runtime, along the arm
        palm = rbox('palm', (0, 0, 0), (0.056, 0.1, 0.092), bevel=0.95, segs=L(d, 3, 2, 1), subdiv=L(d, 1, 0))
        palm = dec_to(palm, B('glove', d))
        finish(palm, 'glove')
        parts = [palm]
        if d < 2:
            thumb = cylinder('thumb', (0, 0.012, -0.036), (sx * -0.012, -0.036, -0.064), 0.019, 0.016, segs=L(d, 8, 5))
            parts.append(finish(thumb, 'glove'))
        cuff = cylinder('gcuff', (0, 0.062, 0), (0, 0.03, 0), 0.047, 0.045, segs=L(d, 12, 8, 6), caps=False)
        parts.append(finish(cuff, 'team'))
        g = join(parts, f'glove{side}')
        rot = Vector((0, -1, 0)).rotation_difference(down)
        for v in g.data.vertices:
            x, y, z = to_runtime(v.co)
            q = rot @ Vector((x, y - 0.045, z))
            v.co = R(w[0] + q.x, w[1] + q.y, q.z)
        rigid_weights(g, 'hand' + side)
        out.append(g)
    return join(out, 'gloves_part')



def build_pants(d):
    nodes = [
        ((0, 0.83, 0.0), (0.134, 0.104)),  # 0 waist (under jacket hem)
        ((0, 0.72, 0.0), (0.146, 0.11)),   # 1 seat
    ]
    edges = [(0, 1)]
    for side in ('L', 'R'):
        sx = -1 if side == 'L' else 1
